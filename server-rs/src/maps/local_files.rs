//! The known maps in the map folders of each user's app installs, synced from the app's local map
//! index. A user's map library can be listed together with (or only as) the maps on one install.

use std::time::Duration;

use async_graphql::InputObject;
use color_eyre::eyre::{self, WrapErr};
use data_encoding::{HEXLOWER, HEXLOWER_PERMISSIVE};
use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};
use sqlx::{PgPool, Postgres, QueryBuilder};
use tracing::{error, info};
use typeshare::typeshare;

use crate::maps::search::LibrarySource;
use crate::maps::{MapHash, SbMapId};
use crate::users::SbUserId;

/// The most file entries (adds and removes together) one sync request may carry.
pub const MAX_SYNC_ENTRIES: usize = 1000;
/// The most hashes one check request may carry.
pub const MAX_CHECK_HASHES: usize = 1000;
/// The most files an install may hold.
const MAX_FILES_PER_INSTALL: usize = 50_000;
/// The most installs a user may have. Syncing from another one deletes the least recently synced.
const MAX_INSTALLS_PER_USER: i64 = 10;
/// Installs that haven't synced for this long are deleted.
const STALE_INSTALL_AGE: Duration = Duration::from_secs(90 * 24 * 60 * 60);
const CLEANUP_STARTUP_DELAY: Duration = Duration::from_secs(5 * 60);
const CLEANUP_INTERVAL: Duration = Duration::from_secs(24 * 60 * 60);
const MAX_INSTALL_ID_LENGTH: usize = 64;
/// The longest folder path accepted, in characters.
const MAX_FOLDER_LENGTH: usize = 1024;

#[derive(Debug, thiserror::Error, PartialEq, Eq)]
pub enum LocalMapFilesError {
    #[error("installId must be 1 to {MAX_INSTALL_ID_LENGTH} letters, digits, '-' or '_'")]
    InvalidInstallId,
    #[error("invalid map hash")]
    InvalidHash,
    #[error("invalid folder")]
    InvalidFolder,
    #[error("too many entries in one request")]
    TooManyEntries,
    #[error("too many files on one install")]
    TooManyFiles,
    #[error("a folder can only be given when listing only the maps on the install")]
    FolderNeedsOnly,
}

/// Identifies one install of the app. Generated by the app and kept across runs.
#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize)]
pub struct InstallId(String);

impl InstallId {
    pub fn parse(value: &str) -> Result<Self, LocalMapFilesError> {
        let valid = !value.is_empty()
            && value.len() <= MAX_INSTALL_ID_LENGTH
            && value
                .bytes()
                .all(|b| b.is_ascii_alphanumeric() || b == b'-' || b == b'_');
        if valid {
            Ok(Self(value.to_string()))
        } else {
            Err(LocalMapFilesError::InvalidInstallId)
        }
    }

    pub fn as_str(&self) -> &str {
        &self.0
    }
}

/// A folder relative to one of the app's map roots, prefixed with the root's key: `/`-separated
/// segments, none of them empty, `.` or `..`, with no backslashes or control characters.
#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize)]
pub struct LocalFolder(String);

impl LocalFolder {
    pub fn parse(value: &str) -> Result<Self, LocalMapFilesError> {
        let valid = value.chars().count() <= MAX_FOLDER_LENGTH
            && !value.chars().any(|c| c == '\\' || c.is_control())
            && value
                .split('/')
                .all(|segment| !segment.is_empty() && segment != "." && segment != "..");
        if valid {
            Ok(Self(value.to_string()))
        } else {
            Err(LocalMapFilesError::InvalidFolder)
        }
    }

    pub fn as_str(&self) -> &str {
        &self.0
    }
}

pub fn parse_map_hash(value: &str) -> Result<MapHash, LocalMapFilesError> {
    let bytes = HEXLOWER_PERMISSIVE
        .decode(value.as_bytes())
        .map_err(|_| LocalMapFilesError::InvalidHash)?;
    Ok(MapHash(
        bytes
            .try_into()
            .map_err(|_| LocalMapFilesError::InvalidHash)?,
    ))
}

/// Limits a listing of an install's maps to one folder.
#[derive(InputObject, Clone, Debug)]
pub struct LocalFolderInput {
    /// The folder, relative to one of the app's map roots and prefixed with that root's key.
    pub path: String,
    /// Whether maps in the folder's subfolders (at any depth) are included.
    pub recursive: bool,
}

/// Includes the known maps on one of the current user's installs in a library listing.
#[derive(InputObject, Clone, Debug)]
pub struct LocalMapsInput {
    pub install_id: String,
    /// List only the maps on the install, leaving out library maps that aren't on it.
    #[graphql(default)]
    pub only: bool,
    /// Only the maps in this folder (requires `only`).
    pub folder: Option<LocalFolderInput>,
}

impl LocalMapsInput {
    pub fn into_source(self) -> Result<LibrarySource, LocalMapFilesError> {
        let install_id = InstallId::parse(&self.install_id)?;
        match (self.only, self.folder) {
            (false, None) => Ok(LibrarySource::WithLocal(install_id)),
            (false, Some(_)) => Err(LocalMapFilesError::FolderNeedsOnly),
            (true, folder) => Ok(LibrarySource::Local(
                install_id,
                folder.map(LocalFolderFilter::new).transpose()?,
            )),
        }
    }
}

/// A validated [`LocalFolderInput`].
#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize)]
pub struct LocalFolderFilter {
    path: LocalFolder,
    recursive: bool,
}

impl LocalFolderFilter {
    pub fn new(input: LocalFolderInput) -> Result<Self, LocalMapFilesError> {
        Ok(Self {
            path: LocalFolder::parse(&input.path)?,
            recursive: input.recursive,
        })
    }

    /// Emits a condition on `{alias}.folder` that matches this folder (and, if recursive, every
    /// folder beneath it), ignoring case.
    pub fn push_condition(&self, qb: &mut QueryBuilder<Postgres>, alias: &str) {
        qb.push(format_args!("(lower({alias}.folder) = lower("));
        qb.push_bind(self.path.0.clone());
        qb.push(")");
        if self.recursive {
            // `lower` leaves the escaped `\`, `%` and `_` alone, so the pattern stays escaped.
            qb.push(format_args!(" OR lower({alias}.folder) LIKE lower("));
            qb.push_bind(format!("{}/%", escape_like(&self.path.0)));
            qb.push(")");
        }
        qb.push(")");
    }
}

/// Escapes `LIKE` pattern characters (with the default `\` escape) so `value` only matches itself.
fn escape_like(value: &str) -> String {
    let mut escaped = String::with_capacity(value.len());
    for c in value.chars() {
        if matches!(c, '\\' | '%' | '_') {
            escaped.push('\\');
        }
        escaped.push(c);
    }
    escaped
}

/// One file in an install's map folders.
#[derive(Debug, Clone, Deserialize)]
#[serde(rename_all = "camelCase")]
#[typeshare]
pub struct LocalMapFileEntry {
    /// The hex-encoded SHA-256 of the file's lowercase extension followed by its contents (the
    /// same as `MapFile.id`).
    pub hash: String,
    /// The file's folder, relative to one of the app's map roots and prefixed with that root's key
    /// (e.g. `documents/Download/UMS`).
    pub folder: String,
}

/// Brings the server's copy of an install's map folders up to date.
#[derive(Debug, Clone, Deserialize)]
#[serde(rename_all = "camelCase")]
#[typeshare]
pub struct SyncLocalMapFilesRequest {
    pub install_id: String,
    /// Deletes every file the server holds for the install before applying `removes` and `adds`.
    /// The first request of a full resync sets it.
    #[serde(default)]
    pub reset: bool,
    #[serde(default)]
    pub removes: Vec<LocalMapFileEntry>,
    #[serde(default)]
    pub adds: Vec<LocalMapFileEntry>,
}

#[derive(Debug, Clone, Serialize, PartialEq, Eq)]
#[serde(rename_all = "camelCase")]
#[typeshare]
pub struct SyncLocalMapFilesResponse {
    /// The hashes in `adds` that match no map. They aren't stored.
    pub unknown_hashes: Vec<String>,
    /// The digest of every file the server now holds for the install: the hex-encoded SHA-256 of
    /// one `{hash}\t{folder}\n` line per file, sorted by their UTF-8 bytes. The app compares it
    /// with its own and resyncs in full if they differ.
    pub digest: String,
    pub file_count: u32,
}

#[derive(Debug, Clone, Deserialize)]
#[serde(rename_all = "camelCase")]
#[typeshare]
pub struct CheckLocalMapFilesRequest {
    pub hashes: Vec<String>,
}

#[derive(Debug, Clone, Serialize, PartialEq, Eq)]
#[serde(rename_all = "camelCase")]
#[typeshare]
pub struct KnownMapFile {
    pub hash: String,
    pub map_id: SbMapId,
}

#[derive(Debug, Clone, Serialize, PartialEq, Eq)]
#[serde(rename_all = "camelCase")]
#[typeshare]
pub struct CheckLocalMapFilesResponse {
    /// The requested hashes that match a map, in no particular order.
    pub known: Vec<KnownMapFile>,
}

/// The digest of a set of (hash, folder) entries: the hex-encoded SHA-256 of one line per entry,
/// `{lowercase hex hash}\t{folder}\n`, with the lines sorted by their UTF-8 bytes. An empty set
/// digests the empty string.
pub fn local_files_digest<'a>(entries: impl IntoIterator<Item = (&'a MapHash, &'a str)>) -> String {
    let mut lines = entries
        .into_iter()
        .map(|(hash, folder)| format!("{}\t{folder}\n", HEXLOWER.encode(&hash.0)))
        .collect::<Vec<_>>();
    lines.sort_unstable();
    let mut hasher = Sha256::new();
    for line in &lines {
        hasher.update(line.as_bytes());
    }
    HEXLOWER.encode(&hasher.finalize())
}

#[derive(Debug, thiserror::Error)]
pub enum LocalMapFilesRepoError {
    #[error(transparent)]
    Invalid(#[from] LocalMapFilesError),
    #[error(transparent)]
    Internal(#[from] eyre::Report),
}

fn parse_entries(
    entries: &[LocalMapFileEntry],
) -> Result<(Vec<Vec<u8>>, Vec<String>), LocalMapFilesError> {
    entries
        .iter()
        .map(|entry| {
            let hash = parse_map_hash(&entry.hash)?;
            let folder = LocalFolder::parse(&entry.folder)?;
            Ok((hash.0.to_vec(), folder.0))
        })
        .collect::<Result<Vec<_>, _>>()
        .map(|pairs| pairs.into_iter().unzip())
}

#[derive(Clone)]
pub struct LocalMapFilesRepo {
    db: PgPool,
}

impl LocalMapFilesRepo {
    pub fn new(db: PgPool) -> Self {
        Self { db }
    }

    /// Applies a sync request from one of `user_id`'s installs, in one transaction.
    pub async fn sync(
        &self,
        user_id: SbUserId,
        request: SyncLocalMapFilesRequest,
    ) -> Result<SyncLocalMapFilesResponse, LocalMapFilesRepoError> {
        let install_id = InstallId::parse(&request.install_id)?;
        if request.adds.len() + request.removes.len() > MAX_SYNC_ENTRIES {
            return Err(LocalMapFilesError::TooManyEntries.into());
        }
        let (remove_hashes, remove_folders) = parse_entries(&request.removes)?;
        let (add_hashes, add_folders) = parse_entries(&request.adds)?;

        let mut tx = self
            .db
            .begin()
            .await
            .wrap_err("Failed to start transaction")?;

        sqlx::query!(
            r#"
                INSERT INTO map_local_installs (user_id, install_id, synced_at)
                VALUES ($1, $2, now())
                ON CONFLICT (user_id, install_id) DO UPDATE SET synced_at = now()
            "#,
            user_id as _,
            install_id.as_str(),
        )
        .execute(&mut *tx)
        .await
        .wrap_err("Failed to record local map install")?;
        // The install just synced is the most recent, so it's never the one evicted.
        sqlx::query!(
            r#"
                DELETE FROM map_local_installs
                WHERE user_id = $1 AND install_id IN (
                    SELECT install_id FROM map_local_installs
                    WHERE user_id = $1
                    ORDER BY synced_at DESC, install_id
                    OFFSET $2
                )
            "#,
            user_id as _,
            MAX_INSTALLS_PER_USER,
        )
        .execute(&mut *tx)
        .await
        .wrap_err("Failed to evict old local map installs")?;

        if request.reset {
            sqlx::query!(
                "DELETE FROM map_local_files WHERE user_id = $1 AND install_id = $2",
                user_id as _,
                install_id.as_str(),
            )
            .execute(&mut *tx)
            .await
            .wrap_err("Failed to reset local map files")?;
        }

        if !remove_hashes.is_empty() {
            sqlx::query!(
                r#"
                    DELETE FROM map_local_files lf
                    USING maps m, unnest($3::bytea[], $4::text[]) AS r(hash, folder)
                    WHERE lf.user_id = $1 AND lf.install_id = $2
                        AND m.hash = r.hash AND lf.map_id = m.id AND lf.folder = r.folder
                "#,
                user_id as _,
                install_id.as_str(),
                &remove_hashes,
                &remove_folders,
            )
            .execute(&mut *tx)
            .await
            .wrap_err("Failed to remove local map files")?;
        }

        let mut unknown_hashes = Vec::new();
        if !add_hashes.is_empty() {
            sqlx::query!(
                r#"
                    INSERT INTO map_local_files (user_id, install_id, map_id, folder)
                    SELECT $1, $2, m.id, a.folder
                    FROM unnest($3::bytea[], $4::text[]) AS a(hash, folder)
                    JOIN maps m ON m.hash = a.hash
                    ON CONFLICT DO NOTHING
                "#,
                user_id as _,
                install_id.as_str(),
                &add_hashes,
                &add_folders,
            )
            .execute(&mut *tx)
            .await
            .wrap_err("Failed to add local map files")?;

            unknown_hashes = sqlx::query_scalar!(
                r#"
                    SELECT DISTINCT a.hash as "hash!: MapHash"
                    FROM unnest($1::bytea[]) AS a(hash)
                    WHERE NOT EXISTS (SELECT 1 FROM maps m WHERE m.hash = a.hash)
                "#,
                &add_hashes,
            )
            .fetch_all(&mut *tx)
            .await
            .wrap_err("Failed to find unknown local map files")?
            .into_iter()
            .map(|hash| HEXLOWER.encode(&hash.0))
            .collect();
        }

        let files = sqlx::query!(
            r#"
                SELECT m.hash as "hash: MapHash", lf.folder
                FROM map_local_files lf
                JOIN maps m ON m.id = lf.map_id
                WHERE lf.user_id = $1 AND lf.install_id = $2
            "#,
            user_id as _,
            install_id.as_str(),
        )
        .fetch_all(&mut *tx)
        .await
        .wrap_err("Failed to load local map files")?;
        if files.len() > MAX_FILES_PER_INSTALL {
            return Err(LocalMapFilesError::TooManyFiles.into());
        }
        let file_count = files.len() as u32;
        let digest = local_files_digest(files.iter().map(|f| (&f.hash, f.folder.as_str())));

        tx.commit()
            .await
            .wrap_err("Failed to commit local map files")?;

        Ok(SyncLocalMapFilesResponse {
            unknown_hashes,
            digest,
            file_count,
        })
    }

    /// Finds the maps that match `hashes`.
    pub async fn check(
        &self,
        request: CheckLocalMapFilesRequest,
    ) -> Result<CheckLocalMapFilesResponse, LocalMapFilesRepoError> {
        if request.hashes.len() > MAX_CHECK_HASHES {
            return Err(LocalMapFilesError::TooManyEntries.into());
        }
        let hashes = request
            .hashes
            .iter()
            .map(|hash| parse_map_hash(hash).map(|hash| hash.0.to_vec()))
            .collect::<Result<Vec<_>, _>>()?;
        let known = sqlx::query!(
            r#"
                SELECT m.hash as "hash: MapHash", m.id as "id: SbMapId"
                FROM maps m
                WHERE m.hash = ANY($1::bytea[])
            "#,
            &hashes,
        )
        .fetch_all(&self.db)
        .await
        .wrap_err("Failed to check local map files")?
        .into_iter()
        .map(|row| KnownMapFile {
            hash: HEXLOWER.encode(&row.hash.0),
            map_id: row.id,
        })
        .collect();
        Ok(CheckLocalMapFilesResponse { known })
    }

    /// Deletes stale installs once soon after startup, then daily.
    pub async fn maintenance_loop(self) {
        tokio::time::sleep(CLEANUP_STARTUP_DELAY).await;
        let mut interval = tokio::time::interval(CLEANUP_INTERVAL);
        interval.set_missed_tick_behavior(tokio::time::MissedTickBehavior::Skip);
        loop {
            interval.tick().await;
            match self.delete_stale_installs().await {
                Ok(0) => {}
                Ok(deleted) => info!("Deleted {deleted} stale local map installs"),
                Err(e) => error!("Deleting stale local map installs failed: {e:?}"),
            }
        }
    }

    /// Deletes the installs (and their files) that haven't synced for [`STALE_INSTALL_AGE`].
    pub async fn delete_stale_installs(&self) -> eyre::Result<u64> {
        let deleted = sqlx::query!(
            "DELETE FROM map_local_installs WHERE synced_at < now() - make_interval(secs => $1)",
            STALE_INSTALL_AGE.as_secs_f64(),
        )
        .execute(&self.db)
        .await
        .wrap_err("Failed to delete stale local map installs")?
        .rows_affected();
        Ok(deleted)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn install_ids_are_short_and_url_safe() {
        assert!(InstallId::parse("V1StGXR8_Z5jdHi6B-myT").is_ok());
        assert_eq!(
            InstallId::parse(""),
            Err(LocalMapFilesError::InvalidInstallId)
        );
        assert_eq!(
            InstallId::parse("has space"),
            Err(LocalMapFilesError::InvalidInstallId)
        );
        assert_eq!(
            InstallId::parse(&"a".repeat(MAX_INSTALL_ID_LENGTH + 1)),
            Err(LocalMapFilesError::InvalidInstallId)
        );
    }

    #[test]
    fn folders_are_relative_slash_separated_paths() {
        for valid in [
            "install",
            "documents/Download/UMS",
            "documents/[EUD] 빠른무한/100%_done",
        ] {
            assert!(LocalFolder::parse(valid).is_ok(), "{valid}");
        }
        for invalid in [
            "",
            "/documents",
            "documents/",
            "documents//UMS",
            "documents/../secret",
            "documents/./UMS",
            "documents\\UMS",
            "documents/a\nb",
        ] {
            assert_eq!(
                LocalFolder::parse(invalid),
                Err(LocalMapFilesError::InvalidFolder),
                "{invalid:?}"
            );
        }
        assert!(LocalFolder::parse(&"a".repeat(MAX_FOLDER_LENGTH)).is_ok());
        assert!(LocalFolder::parse(&"a".repeat(MAX_FOLDER_LENGTH + 1)).is_err());
    }

    #[test]
    fn hashes_are_64_hex_characters() {
        let hex = "ab".repeat(32);
        assert_eq!(parse_map_hash(&hex).unwrap().0, [0xab; 32]);
        assert_eq!(parse_map_hash(&hex.to_uppercase()).unwrap().0, [0xab; 32]);
        assert_eq!(
            parse_map_hash(&"ab".repeat(31)),
            Err(LocalMapFilesError::InvalidHash)
        );
        assert_eq!(
            parse_map_hash(&"zz".repeat(32)),
            Err(LocalMapFilesError::InvalidHash)
        );
    }

    #[test]
    fn local_maps_input_picks_the_source() {
        let input = |only, folder: Option<&str>| LocalMapsInput {
            install_id: "abc".to_string(),
            only,
            folder: folder.map(|path| LocalFolderInput {
                path: path.to_string(),
                recursive: false,
            }),
        };
        let install = InstallId::parse("abc").unwrap();
        assert_eq!(
            input(false, None).into_source(),
            Ok(LibrarySource::WithLocal(install.clone()))
        );
        assert_eq!(
            input(true, None).into_source(),
            Ok(LibrarySource::Local(install, None))
        );
        assert!(matches!(
            input(true, Some("documents/UMS")).into_source(),
            Ok(LibrarySource::Local(_, Some(_)))
        ));
        assert_eq!(
            input(false, Some("documents/UMS")).into_source(),
            Err(LocalMapFilesError::FolderNeedsOnly)
        );
        assert_eq!(
            input(true, Some("../x")).into_source(),
            Err(LocalMapFilesError::InvalidFolder)
        );
    }

    #[test]
    fn like_escaping_covers_every_pattern_character() {
        assert_eq!(escape_like("a_b%c\\d"), "a\\_b\\%c\\\\d");
        assert_eq!(escape_like("plain/UMS"), "plain/UMS");
    }

    fn folder_sql(path: &str, recursive: bool) -> String {
        let filter = LocalFolderFilter::new(LocalFolderInput {
            path: path.to_string(),
            recursive,
        })
        .unwrap();
        let mut qb = QueryBuilder::<Postgres>::new("");
        filter.push_condition(&mut qb, "lf");
        qb.sql().as_str().to_string()
    }

    #[test]
    fn folder_conditions_match_directly_or_beneath() {
        assert_eq!(
            folder_sql("documents/UMS", false),
            "(lower(lf.folder) = lower($1))"
        );
        assert_eq!(
            folder_sql("documents/UMS", true),
            "(lower(lf.folder) = lower($1) OR lower(lf.folder) LIKE lower($2))"
        );
    }

    #[test]
    fn digest_ignores_order_and_covers_folders() {
        let a = MapHash([1; 32]);
        let b = MapHash([2; 32]);
        let forward = local_files_digest([(&a, "install"), (&b, "documents/UMS")]);
        let backward = local_files_digest([(&b, "documents/UMS"), (&a, "install")]);
        assert_eq!(forward, backward);
        assert_ne!(
            forward,
            local_files_digest([(&a, "install"), (&b, "documents/ums")])
        );
        // The empty set digests the empty string.
        assert_eq!(
            local_files_digest([]),
            "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855"
        );
        // One entry digests exactly its line.
        let line = format!("{}\tinstall\n", "01".repeat(32));
        assert_eq!(
            local_files_digest([(&a, "install")]),
            HEXLOWER.encode(&Sha256::digest(line.as_bytes()))
        );
    }
}
